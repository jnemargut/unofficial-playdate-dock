static const uint8_t blank[8] = {0,0,0,0,0,0,0,0};

const uint8_t *pd_font_glyph(char c) {
	if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
	if (c < 32 || c > 95) return blank;
	return font8x8[(int)c - 32];
}
